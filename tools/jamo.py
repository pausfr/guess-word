"""한글 음절 → 기본 자모 완전 분해 (게임 규칙과 동일)."""
INITIAL = ["ㄱ","ㄲ","ㄴ","ㄷ","ㄸ","ㄹ","ㅁ","ㅂ","ㅃ","ㅅ","ㅆ","ㅇ","ㅈ","ㅉ","ㅊ","ㅋ","ㅌ","ㅍ","ㅎ"]
MEDIAL = ["ㅏ","ㅐ","ㅑ","ㅒ","ㅓ","ㅔ","ㅕ","ㅖ","ㅗ","ㅘ","ㅙ","ㅚ","ㅛ","ㅜ","ㅝ","ㅞ","ㅟ","ㅠ","ㅡ","ㅢ","ㅣ"]
FINAL = ["","ㄱ","ㄲ","ㄳ","ㄴ","ㄵ","ㄶ","ㄷ","ㄹ","ㄺ","ㄻ","ㄼ","ㄽ","ㄾ","ㄿ","ㅀ","ㅁ","ㅂ","ㅄ","ㅅ","ㅆ","ㅇ","ㅈ","ㅊ","ㅋ","ㅌ","ㅍ","ㅎ"]
BASE = {
    "ㄲ":"ㄱㄱ","ㄸ":"ㄷㄷ","ㅃ":"ㅂㅂ","ㅆ":"ㅅㅅ","ㅉ":"ㅈㅈ",
    "ㄳ":"ㄱㅅ","ㄵ":"ㄴㅈ","ㄶ":"ㄴㅎ","ㄺ":"ㄹㄱ","ㄻ":"ㄹㅁ","ㄼ":"ㄹㅂ","ㄽ":"ㄹㅅ","ㄾ":"ㄹㅌ","ㄿ":"ㄹㅍ","ㅀ":"ㄹㅎ","ㅄ":"ㅂㅅ",
    "ㅐ":"ㅏㅣ","ㅒ":"ㅑㅣ","ㅔ":"ㅓㅣ","ㅖ":"ㅕㅣ","ㅘ":"ㅗㅏ","ㅙ":"ㅗㅏㅣ","ㅚ":"ㅗㅣ","ㅝ":"ㅜㅓ","ㅞ":"ㅜㅓㅣ","ㅟ":"ㅜㅣ","ㅢ":"ㅡㅣ",
}
def decompose(word):
    """순수 한글 음절 문자열이면 자모 문자열, 아니면 None."""
    out = []
    for ch in word:
        c = ord(ch) - 0xAC00
        if not 0 <= c < 11172:
            return None
        i, rest = divmod(c, 588)
        m, f = divmod(rest, 28)
        for j in (INITIAL[i], MEDIAL[m], FINAL[f]):
            out.append(BASE.get(j, j))
    return "".join(out)
